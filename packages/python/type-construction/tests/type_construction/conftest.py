"""Shared fixtures: generated secured NATS material and a disposable secured NATS server.

Prerequisites: ``openssl`` and ``docker`` on the host. The material is generated by
``scripts/generate_nats_material.py`` into a session temporary directory, so no committed or
development secret is used. The server runs the pinned ``nats`` image with TLS before any
protocol exchange, TLS on its WebSocket listener, the generated operator and disposable
in-memory storage; it is removed after the session. Missing prerequisites fail the fixtures.

``material`` maps ``certificate_authority``, ``application_credentials``, ``setup_credentials``,
``untrusted_certificate_authority`` and ``untrusted_credentials`` to generated files.
``secured_nats`` maps ``tls_port`` and ``wss_port`` to the server's host ports on 127.0.0.1;
``server_logs`` returns the server's log so far.
"""

import shutil
import subprocess
import sys
import time
import uuid
from collections.abc import Callable, Iterator
from pathlib import Path

import pytest

REPOSITORY = Path(__file__).resolve().parents[5]
GENERATOR = REPOSITORY / "scripts" / "generate_nats_material.py"
NATS_IMAGE = (
    "nats:2.15.2-alpine@sha256:823e7f1d6d8ffe3b30dbd73d4a06bbb939acf94929f7fdf224404da7a05bafb5"
)
READY_TIMEOUT = 30.0


def _docker(*arguments: str) -> str:
    """Run docker and return its combined output; the NATS server logs to stderr."""
    executable = shutil.which("docker")
    if executable is None:
        pytest.fail("docker is required to run the secured NATS server for these tests")
    result = subprocess.run(  # noqa: S603 - fixed docker invocation with test-controlled arguments
        [executable, *arguments], check=True, capture_output=True, text=True
    )
    return result.stdout + result.stderr


@pytest.fixture(scope="session")
def material(tmp_path_factory: pytest.TempPathFactory) -> dict[str, Path]:
    output = tmp_path_factory.mktemp("secured-nats") / "material"
    result = subprocess.run(  # noqa: S603 - the interpreter and script are fixed test inputs
        [sys.executable, "-I", str(GENERATOR), str(output)],
        check=False,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        pytest.fail(f"material generation failed:\n{result.stdout}\n{result.stderr}")
    return {
        "server": output / "nats",
        "certificate_authority": output / "client" / "ca.pem",
        "application_credentials": output / "client" / "application.creds",
        "setup_credentials": output / "client" / "setup.creds",
        "untrusted_certificate_authority": output / "untrusted" / "ca.pem",
        "untrusted_credentials": output / "untrusted" / "application.creds",
    }


def _host_port(name: str, container_port: str) -> int:
    published = _docker("port", name, container_port).strip().splitlines()[0]
    return int(published.rsplit(":", 1)[1])


@pytest.fixture(scope="session")
def _secured_nats_container(material: dict[str, Path]) -> Iterator[str]:
    name = f"tca-test-nats-{uuid.uuid4().hex[:12]}"
    _docker(
        "run",
        "--detach",
        "--rm",
        "--name",
        name,
        "--publish",
        "127.0.0.1:0:4222",
        "--publish",
        "127.0.0.1:0:8443",
        "--volume",
        f"{material['server']}:/etc/nats:ro",
        "--tmpfs",
        "/data",
        NATS_IMAGE,
        "-c",
        "/etc/nats/nats-server.conf",
    )
    try:
        deadline = time.monotonic() + READY_TIMEOUT
        while "Server is ready" not in _docker("logs", name):
            if time.monotonic() > deadline:
                pytest.fail(f"secured NATS did not become ready:\n{_docker('logs', name)}")
            time.sleep(0.2)
        yield name
    finally:
        subprocess.run(  # noqa: S603 - removal must run even if the server never became ready
            [shutil.which("docker") or "docker", "rm", "--force", name],
            check=False,
            capture_output=True,
        )


@pytest.fixture(scope="session")
def secured_nats(_secured_nats_container: str) -> dict[str, int]:
    return {
        "tls_port": _host_port(_secured_nats_container, "4222/tcp"),
        "wss_port": _host_port(_secured_nats_container, "8443/tcp"),
    }


@pytest.fixture(scope="session")
def server_logs(_secured_nats_container: str) -> Callable[[], str]:
    def logs() -> str:
        return _docker("logs", _secured_nats_container)

    return logs
