"""Shared fixtures: generated secured NATS material and disposable secured NATS servers.

Prerequisites: ``openssl`` and ``docker`` on the host. The material is generated by
``scripts/generate_nats_material.py`` into a session temporary directory, so no committed or
development secret is used. Servers run the pinned ``nats`` image with TLS before any protocol
exchange, TLS on the WebSocket listener, the generated operator and disposable in-memory storage;
they are removed after use. Missing prerequisites fail the fixtures. Every external command is
bounded, and a cleanup failure is attached to the original failure instead of replacing it.

``material`` maps ``certificate_authority``, ``application_credentials``, ``setup_credentials``,
``untrusted_certificate_authority`` and ``untrusted_credentials`` to generated files, ``server``
to the server partition and ``root`` to the generated directory. ``secured_nats`` maps
``tls_port`` and ``wss_port`` to the session server's host ports on 127.0.0.1; ``server_logs``
returns that server's log so far. ``secured_server`` is a context manager starting a further
server from the same material, for tests that stop and restart one.
"""

import contextlib
import shutil
import socket
import subprocess
import sys
import time
import uuid
from collections.abc import Callable, Generator, Iterator
from dataclasses import dataclass
from pathlib import Path

import pytest

REPOSITORY = Path(__file__).resolve().parents[5]
GENERATOR = REPOSITORY / "scripts" / "generate_nats_material.py"
NATS_IMAGE = (
    "nats:2.15.2-alpine@sha256:823e7f1d6d8ffe3b30dbd73d4a06bbb939acf94929f7fdf224404da7a05bafb5"
)
READY_TIMEOUT = 30.0
COMMAND_TIMEOUT = 60.0
GENERATION_TIMEOUT = 300.0


def docker(*arguments: str, timeout: float = COMMAND_TIMEOUT) -> str:
    """Run docker within a bound and return its combined output; the server logs to stderr."""
    executable = shutil.which("docker")
    if executable is None:
        pytest.fail("docker is required to run the secured NATS server for these tests")
    result = subprocess.run(  # noqa: S603 - fixed docker invocation with test-controlled arguments
        [executable, *arguments], check=True, capture_output=True, text=True, timeout=timeout
    )
    return result.stdout + result.stderr


def generate_material(output: Path, *arguments: str) -> subprocess.CompletedProcess[str]:
    """Run the material generator as the setup tooling does, within a bound."""
    return subprocess.run(  # noqa: S603 - the interpreter and script are fixed test inputs
        [sys.executable, "-I", str(GENERATOR), str(output), *arguments],
        check=False,
        capture_output=True,
        text=True,
        timeout=GENERATION_TIMEOUT,
    )


def free_port() -> int:
    """A host port that is free now; used where a server must keep its port across a restart."""
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
        probe.bind(("127.0.0.1", 0))
        return probe.getsockname()[1]


@pytest.fixture(scope="session")
def repository() -> Path:
    return REPOSITORY


@pytest.fixture(scope="session")
def generator() -> Callable[..., subprocess.CompletedProcess[str]]:
    """Run the material generator on a disposable output directory: ``generator(output, *args)``."""
    return generate_material


@pytest.fixture(scope="session")
def docker_command() -> Callable[..., str]:
    """Run a bounded docker command and return its combined output."""
    return docker


@pytest.fixture(scope="session")
def material(tmp_path_factory: pytest.TempPathFactory) -> dict[str, Path]:
    output = tmp_path_factory.mktemp("secured-nats") / "material"
    result = generate_material(output)
    if result.returncode != 0:
        pytest.fail(f"material generation failed:\n{result.stdout}\n{result.stderr}")
    return {
        "root": output,
        "server": output / "server",
        "certificate_authority": output / "application" / "ca.pem",
        "application_credentials": output / "application" / "application.creds",
        "setup_credentials": output / "provisioning" / "setup.creds",
        "untrusted_certificate_authority": output / "untrusted" / "ca.pem",
        "untrusted_credentials": output / "untrusted" / "application.creds",
    }


@dataclass(frozen=True)
class SecuredServer:
    """A running disposable secured server and the host ports its listeners are published on."""

    name: str
    tls_port: int
    wss_port: int

    def logs(self) -> str:
        return docker("logs", self.name)

    def stop(self) -> None:
        """Stop the server process; the container and its published ports remain."""
        docker("stop", self.name)

    def start(self) -> None:
        """Start the stopped server again and wait until it reports readiness anew."""
        ready_before = self.logs().count("Server is ready")
        docker("start", self.name)
        _wait_ready(self.name, ready_before + 1)


def _host_port(name: str, container_port: str) -> int:
    published = docker("port", name, container_port).strip().splitlines()[0]
    return int(published.rsplit(":", 1)[1])


def _wait_ready(name: str, count: int = 1) -> None:
    deadline = time.monotonic() + READY_TIMEOUT
    while docker("logs", name).count("Server is ready") < count:
        if time.monotonic() > deadline:
            pytest.fail(f"secured NATS {name} did not become ready:\n{docker('logs', name)}")
        time.sleep(0.2)


@contextlib.contextmanager
def _secured_server(server_material: Path, *, keep_port: bool = False) -> Generator[SecuredServer]:
    """Start a disposable secured server; remove it afterwards, keeping any test failure.

    With ``keep_port`` the TLS listener is published on a port chosen now, so the server keeps
    its address across a stop and start; otherwise Docker assigns one.
    """
    name = f"tca-test-nats-{uuid.uuid4().hex[:12]}"
    docker(
        "run",
        "--detach",
        "--name",
        name,
        "--publish",
        f"127.0.0.1:{free_port() if keep_port else 0}:4222",
        "--publish",
        "127.0.0.1:0:8443",
        "--volume",
        f"{server_material}:/etc/nats:ro",
        "--tmpfs",
        "/data",
        NATS_IMAGE,
        "-c",
        "/etc/nats/nats-server.conf",
    )
    try:
        _wait_ready(name)
        yield SecuredServer(name, _host_port(name, "4222/tcp"), _host_port(name, "8443/tcp"))
    except BaseException as failure:
        try:
            docker("rm", "--force", name)
        except Exception as cleanup_failure:
            failure.add_note(f"removing {name} also failed: {cleanup_failure!r}")
        raise
    else:
        docker("rm", "--force", name)


@pytest.fixture(scope="session")
def _session_server(material: dict[str, Path]) -> Iterator[SecuredServer]:
    with _secured_server(material["server"]) as server:
        yield server


@pytest.fixture(scope="session")
def secured_nats(_session_server: SecuredServer) -> dict[str, int]:
    return {"tls_port": _session_server.tls_port, "wss_port": _session_server.wss_port}


@pytest.fixture(scope="session")
def server_logs(_session_server: SecuredServer) -> Callable[[], str]:
    return _session_server.logs


@pytest.fixture
def secured_server(
    material: dict[str, Path],
) -> Callable[..., contextlib.AbstractContextManager[SecuredServer]]:
    """Start further secured servers from the session material, for example to restart one."""

    def start(*, keep_port: bool = False) -> contextlib.AbstractContextManager[SecuredServer]:
        return _secured_server(material["server"], keep_port=keep_port)

    return start
